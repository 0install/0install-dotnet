using System.Text;
using System.Text.RegularExpressions;
using NanoByte.Common.Streams;
using ZeroInstall.Model.Selection;
using ZeroInstall.Store.Implementations;

namespace ZeroInstall.Services.Executors;

/// <summary>
/// Generates PowerShell scripts that launch a <see cref="Selections"/> document on Windows from a directory containing copies of its implementations.
/// </summary>
/// <param name="implementationStore">Not used for locating implementations. Required by <see cref="EnvironmentBuilder"/>.</param>
/// <param name="getRelativePath">Returns the path of an implementation's directory relative to the directory the launcher script is placed in.</param>
/// <remarks>
/// <see cref="ExecutableInVar"/> and <see cref="ExecutableInPath"/> bindings use copies of the run-environment executable also used by <see cref="Executor"/>,
/// with the command-lines to run passed via environment variables set by the launcher script.
/// </remarks>
internal sealed partial class PowerShellLauncherScriptBuilder(IImplementationStore implementationStore, Func<ImplementationSelection, string> getRelativePath)
    : LauncherScriptBuilder(implementationStore, getRelativePath)
{
    /// <summary>
    /// PowerShell variable holding the absolute path of the directory containing the launcher script.
    /// </summary>
    private const string DirVar = "$_zeroinstall_dir";

    /// <summary>
    /// PowerShell variable holding the command-line currently being built.
    /// </summary>
    private const string CmdVar = "$_zeroinstall_cmd";

    /// <summary>
    /// The default separator for lists of paths in environment variables on Windows.
    /// </summary>
    private const string PathListSeparator = ";";

    private readonly List<string> _environmentStatements = [];

    /// <inheritdoc/>
    public override string LauncherExtension => ".ps1";

    /// <inheritdoc/>
    /// <remarks>Windows PowerShell treats scripts without a byte order mark as encoded in the system's legacy code page.</remarks>
    public override Encoding Encoding { get; } = new UTF8Encoding(encoderShouldEmitUTF8Identifier: true);

    /// <inheritdoc/>
    private protected override char DirectorySeparator => '\\';

    /// <inheritdoc/>
    private protected override void ApplyEnvironmentValue(EnvironmentBinding binding, string newValue)
    {
        string name = RequireVariableName(binding.Name, "<environment>");
        string variable = GetVariable(name);
        string separator = string.IsNullOrEmpty(binding.Separator) ? PathListSeparator : binding.Separator;

        // Set the default value if the variable is not already set on the system
        if (binding.Default != null)
            _environmentStatements.Add($"if ($null -eq {variable}) {{ {SetVariable(name, QuoteLiteral(binding.Default))} }}");

        _environmentStatements.Add(binding.Mode switch
        {
            EnvironmentMode.Replace => SetVariable(name, QuoteLiteral(newValue)),
            EnvironmentMode.Prepend => $"if ({variable}) {{ {SetVariable(name, $"{QuoteLiteral(newValue + separator)} + {variable}")} }} else {{ {SetVariable(name, QuoteLiteral(newValue))} }}",
            EnvironmentMode.Append => $"if ({variable}) {{ {SetVariable(name, $"{variable} + {QuoteLiteral(separator + newValue)}")} }} else {{ {SetVariable(name, QuoteLiteral(newValue))} }}",
            _ => throw new InvalidOperationException($"Unknown {nameof(EnvironmentBinding)} value: {binding.Mode}")
        });
    }

    /// <inheritdoc/>
    private protected override string DeployExecutable(string name)
        => $@"{RootMarker}{BinDir}\{name}.exe";

    /// <inheritdoc/>
    private protected override void SetExecutableVariable(string name, string exePath)
        => _environmentStatements.Add(SetVariable(RequireVariableName(name, "<executable-in-var>"), QuoteLiteral(exePath)));

    /// <inheritdoc/>
    private protected override void AddExecutableToSearchPath(string exePath)
        => _environmentStatements.Add(SetVariable("Path", $"{QuoteLiteral(RootMarker + BinDir + PathListSeparator)} + {GetVariable("Path")}"));

    /// <inheritdoc/>
    public override string GetLauncher()
    {
        var commandLine = RequireMainCommandLine();

        var script = new StringBuilder();
        script.Append("""
            # Generated by Zero Install. Changes will be overwritten when the directory is updated.
            $ErrorActionPreference = 'Stop'
            $_zeroinstall_dir = $PSScriptRoot

            # Escapes and joins arguments for a Windows command-line, starting at a specific index
            function _zeroinstall_join([string[]]$cmd, [int]$skip) {
                $(for ($i = $skip; $i -lt $cmd.Count; $i++) {
                    $arg = $cmd[$i]
                    if ($arg -and $arg -notmatch '[\s"]') { $arg }
                    else { '"' + ($arg -replace '(\\*)"', '$1$1\"' -replace '(\\+)$', '$1$1') + '"' }
                }) -join ' '
            }


            """);

        foreach (string statement in _environmentStatements)
            script.AppendLine(statement);

        // Pass command-lines to run-environment executables, after all bindings have been applied, like Executor does
        foreach ((string name, var runEnvCommandLine) in PendingRunEnvs)
        {
            script.AppendLine();
            AppendCommandLine(script, runEnvCommandLine.ToList());
            script.AppendLine(SetVariable("ZEROINSTALL_RUNENV_FILE_" + name, $"{CmdVar}[0]"));
            script.AppendLine(SetVariable("ZEROINSTALL_RUNENV_ARGS_" + name, $"(_zeroinstall_join {CmdVar} 1)"));
        }

        script.AppendLine();
        AppendCommandLine(script, commandLine);
        script.AppendLine($$"""
            $_zeroinstall_start = New-Object System.Diagnostics.ProcessStartInfo
            $_zeroinstall_start.FileName = {{CmdVar}}[0]
            $_zeroinstall_start.Arguments = _zeroinstall_join ({{CmdVar}} + $args) 1
            $_zeroinstall_start.UseShellExecute = $false
            """);
        script.AppendLine(WorkingDirectory is {} workingDirectory
            ? $"$_zeroinstall_start.WorkingDirectory = {QuoteLiteral(workingDirectory)}"
            // Process.Start() would otherwise use the process-wide current directory, which PowerShell does not keep in sync with its own location
            : "$_zeroinstall_start.WorkingDirectory = (Get-Location -PSProvider FileSystem).ProviderPath");
        script.AppendLine("""
            $_zeroinstall_process = [System.Diagnostics.Process]::Start($_zeroinstall_start)
            $_zeroinstall_process.WaitForExit()
            exit $_zeroinstall_process.ExitCode
            """);

        return script.ToString().Replace("\r\n", "\n").Replace("\n", "\r\n");
    }

    /// <inheritdoc/>
    public override IEnumerable<(string name, byte[] content)> GetExecutables()
    {
        RequireMainCommandLine();

        // The run-environment executable determines which environment variables to read from its own file name
        foreach ((string name, _) in PendingRunEnvs)
            yield return (name + ".exe", RunEnvExecutable);
    }

    /// <inheritdoc/>
    /// <remarks>
    /// Generates a batch file, since PowerShell scripts cannot be started by double-clicking or from cmd.exe and may be blocked by the execution policy.
    /// Refers to the launcher script via its own path (<c>%~dpn0</c>), so it contains no file names that would need to be encoded for cmd.exe.
    /// </remarks>
    public override (string extension, byte[] content)? GetWrapper()
        => (".cmd", Encoding.ASCII.GetBytes("""
            @echo off
            rem Generated by Zero Install. Changes will be overwritten when the directory is updated.
            "%SystemRoot%\System32\WindowsPowerShell\v1.0\powershell.exe" -NoProfile -ExecutionPolicy Bypass -File "%~dpn0.ps1" %*
            exit /b %ERRORLEVEL%

            """.Replace("\r\n", "\n").Replace("\n", "\r\n")));

    private static byte[] RunEnvExecutable => _runEnvExecutable ??= typeof(Executor).GetEmbeddedBytes("runenv.exe.template");
    private static byte[]? _runEnvExecutable;

    /// <summary>
    /// Appends code that stores a command-line in <see cref="CmdVar"/> as an array of strings,
    /// with environment variables expanded when the script runs, matching <c>EnvironmentBuilder.ExpandCommandLine()</c>.
    /// </summary>
    private void AppendCommandLine(StringBuilder script, IReadOnlyList<ArgBase> commandLine)
    {
        if (commandLine is []) throw new ExecutorException(Resources.CommandLineEmpty);

        if (!commandLine.OfType<ForEachArgs>().Any())
        {
            script.AppendLine($"{CmdVar} = @({string.Join(", ", commandLine.Cast<Arg>().Select(arg => QuoteArg(arg.Value)))})");
            return;
        }

        script.AppendLine($"{CmdVar} = @()");
        foreach (var part in commandLine)
        {
            switch (part)
            {
                case Arg arg:
                    script.AppendLine($"{CmdVar} += {QuoteArg(arg.Value)}");
                    break;

                case ForEachArgs forEach:
                    string itemFrom = RequireVariableName(forEach.ItemFrom, "<for-each>");
                    string separator = forEach.Separator ?? PathListSeparator;
                    string items = separator.Length == 0
                        ? $"@({GetVariable(itemFrom)})"
                        : $"({GetVariable(itemFrom)} -csplit {QuoteLiteral(Regex.Escape(separator))})";
                    script.AppendLine($$"""
                        foreach ($_zeroinstall_item in {{items}}) {
                            if (-not $_zeroinstall_item) { continue }
                            {{SetVariable("item", "$_zeroinstall_item")}}
                            {{CmdVar}} += @({{string.Join(", ", forEach.Arguments.Select(arg => QuoteArg(arg.Value)))}})
                        }
                        {{SetVariable("item", "$null")}}
                        """);
                    break;

                default:
                    throw new NotSupportedException($"Unknown command-line part: {part}");
            }
        }
    }

    /// <summary>
    /// Converts a string into a PowerShell expression evaluating to that string, with no variables being expanded.
    /// Replaces <see cref="LauncherScriptBuilder.RootMarker"/> with a reference to the directory containing the launcher script.
    /// </summary>
    private static string QuoteLiteral(string value)
        => Concat(LiteralExpressions(value));

    /// <summary>
    /// Converts a string into PowerShell expressions that evaluate to that string when concatenated.
    /// </summary>
    private static IEnumerable<string> LiteralExpressions(string value)
    {
        string[] parts = value.Split([RootMarker], StringSplitOptions.None);
        for (int i = 0; i < parts.Length; i++)
        {
            string part = parts[i];
            if (i > 0)
            {
                yield return DirVar;
                part = @"\" + part; // The marker stands for the directory followed by a separator
            }
            foreach (string expression in SplitLineBreaks(part))
                yield return expression;
        }
    }

    /// <summary>
    /// Converts a string into single-quoted PowerShell string literals, with line breaks as separate escape sequences.
    /// Keeps line breaks that are part of values apart from the line endings of the script itself.
    /// </summary>
    private static IEnumerable<string> SplitLineBreaks(string value)
    {
        int start = 0;
        for (int i = 0; i < value.Length; i++)
        {
            if (value[i] is not ('\r' or '\n')) continue;

            if (i > start) yield return SingleQuote(value[start..i]);
            yield return value[i] == '\r' ? "\"`r\"" : "\"`n\"";
            start = i + 1;
        }
        if (start < value.Length) yield return SingleQuote(value[start..]);
    }

    /// <summary>
    /// Converts a string into a single-quoted PowerShell string literal.
    /// </summary>
    private static string SingleQuote(string value)
    {
        var result = new StringBuilder("'");
        foreach (char c in value)
        {
            // PowerShell treats typographic single quotes like ASCII ones
            if (c is '\'' or '‘' or '’' or '‚' or '‛') result.Append(c);
            result.Append(c);
        }
        return result.Append('\'').ToString();
    }

    /// <summary>
    /// Combines PowerShell expressions into a single expression that evaluates to a string.
    /// </summary>
    private static string Concat(IReadOnlyCollection<string> expressions)
        => expressions.Count switch
        {
            0 => "''",
            1 when expressions.First().StartsWith("'") => expressions.First(),
            _ when expressions.First().StartsWith("'") || expressions.First() == DirVar => $"({string.Join(" + ", expressions)})",
            // Ensures the result is a string, even if the first expression evaluates to $null
            _ => $"('' + {string.Join(" + ", expressions)})"
        };

    private static string Concat(IEnumerable<string> expressions)
        => Concat(expressions.ToList());

    /// <summary>
    /// Converts an <see cref="Arg"/> value into a PowerShell expression evaluating to a string,
    /// with environment variables expanded when the script runs, matching <c>OSUtils.ExpandVariables()</c>.
    /// </summary>
    private string QuoteArg(string value)
        => Concat(ParseArg(value).SelectMany(PartExpressions));

    /// <summary>
    /// Converts a part of an <see cref="Arg"/> value into PowerShell expressions that evaluate to its value when concatenated.
    /// </summary>
    private static IEnumerable<string> PartExpressions(ArgPart part)
        => part switch
        {
            LiteralPart literal => LiteralExpressions(literal.Value),
            VariablePart {Operator: null} variable => new[] {GetVariable(variable.Name)},
            VariablePart {Operator: ":-"} variable => new[] {$"$(if ({GetVariable(variable.Name)}) {{ {GetVariable(variable.Name)} }} else {{ {Concat(variable.Default!.SelectMany(PartExpressions))} }})"},
            VariablePart variable => new[] {$"$(if ($null -ne {GetVariable(variable.Name)}) {{ {GetVariable(variable.Name)} }} else {{ {Concat(variable.Default!.SelectMany(PartExpressions))} }})"},
            _ => throw new NotSupportedException($"Unknown argument part: {part}")
        };

    /// <summary>
    /// Returns a PowerShell expression that reads an environment variable.
    /// </summary>
    private static string GetVariable(string name)
        => SimpleNameRegex().IsMatch(name)
            ? $"$env:{name}"
            : $"[Environment]::GetEnvironmentVariable({SingleQuote(name)})";

    /// <summary>
    /// Returns a PowerShell statement that sets an environment variable, or removes it if <paramref name="expression"/> evaluates to <c>$null</c> or an empty string.
    /// </summary>
    private static string SetVariable(string name, string expression)
        => SimpleNameRegex().IsMatch(name)
            ? $"$env:{name} = {expression}"
            : $"[Environment]::SetEnvironmentVariable({SingleQuote(name)}, {expression})";

    /// <inheritdoc/>
    /// <remarks>Windows allows almost any character in environment variable names, except for <c>=</c>.</remarks>
    private protected override bool IsValidVariableName(string? name)
        => !string.IsNullOrEmpty(name) && name!.IndexOfAny(['=', '\0']) < 0;

    /// <summary>
    /// Matches environment variable names that can be used with the short <c>$env:NAME</c> syntax.
    /// </summary>
    private const string SimpleNamePattern = "^[A-Za-z_][A-Za-z0-9_]*$";

#if NET
    [GeneratedRegex(SimpleNamePattern)]
    private static partial Regex SimpleNameRegex();
#else
    private static readonly Regex _simpleNameRegex = new(SimpleNamePattern);
    private static Regex SimpleNameRegex() => _simpleNameRegex;
#endif
}
