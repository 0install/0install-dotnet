    [Fact]
    public void FileTypesShareHandler()
    {
        var fileType1 = CreateFileType("a", new Capabilities.FileTypeExtension {Value = ".txt"});
        var fileType2 = CreateFileType("b", new Capabilities.FileTypeExtension {Value = ".img"});
        FileType.Register(_target, fileType1, _iconStore, machineWide: false);
        FileType.Register(_target, fileType2, _iconStore, machineWide: false);
        GetValue(Handlers.Single(), "MimeType").Should().Be("text/plain;image/x-high;");

        FileType.Unregister(fileType1, machineWide: false);
        GetValue(Handlers.Single(), "MimeType").Should().Be("image/x-high;");

        FileType.Unregister(fileType2, machineWide: false);
        Handlers.Should().BeEmpty();
    }

    [Fact]
    public void FileTypeDefault()
    {
        Directory.CreateDirectory(HomeFile(".config"));
        File.WriteAllText(MimeAppsPath, "[Default Applications]\nimage/x-high=other.desktop;\n");

        var fileType = CreateFileType("a", new Capabilities.FileTypeExtension {Value = ".img"}, new Capabilities.FileTypeExtension {Value = ".bin"});
        FileType.Register(_target, fileType, _iconStore, machineWide: false);
        FileType.Register(_target, fileType, _iconStore, machineWide: false, accessPoint: true);
        string desktopID = Paths.FileName(Handlers.Single());
        File.ReadAllText(MimeAppsPath).Should().Be($"[Default Applications]\nimage/x-high={desktopID};other.desktop;\n", because: "generic MIME types should not get new defaults");

        FileType.Unregister(fileType, machineWide: false, accessPoint: true);
        File.ReadAllText(MimeAppsPath).Should().Be("[Default Applications]\nimage/x-high=other.desktop;\n");
        GetValue(Handlers.Single(), "MimeType").Should().Be("image/x-high;application/octet-stream;", because: "still registered as a candidate");

        FileType.Unregister(fileType, machineWide: false);
        Handlers.Should().BeEmpty();
    }

    [Fact]
    public void FileTypeDefaultPreservesUserChoices()
    {
        var fileType = CreateFileType("a", new Capabilities.FileTypeExtension {Value = ".img"});
        FileType.Register(_target, fileType, _iconStore, machineWide: false, accessPoint: true);
        string desktopID = Paths.FileName(Handlers.Single());
        File.AppendAllText(MimeAppsPath, $"image/x-other={desktopID};\n"); // Chosen by user in file manager

        FileType.Register(_target, fileType, _iconStore, machineWide: false, accessPoint: true);
        Paths.FileName(Handlers.Single()).Should().Be(desktopID);
        File.ReadAllText(MimeAppsPath).Should().Contain($"\nimage/x-other={desktopID};\n", because: "reapplying should not remove associations made by the user")
                                      .And.Contain($"\nimage/x-high={desktopID};\n");

        FileType.Unregister(fileType, machineWide: false, accessPoint: true);
        Handlers.Should().BeEmpty();
        File.ReadAllText(MimeAppsPath).Should().NotContain(desktopID);
    }

