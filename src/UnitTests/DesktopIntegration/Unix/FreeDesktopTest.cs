    private static Capabilities.FileType CreateFileType(string id, params Capabilities.FileTypeExtension[] extensions)
    {
        var fileType = new Capabilities.FileType {ID = id, Verbs = {new() {Name = Capabilities.Verb.NameOpen}}};
        fileType.Extensions.AddRange(extensions);
        return fileType;
    }

    [Fact]
    public void FileTypeKnown()
    {
        var fileType = CreateFileType("a", new Capabilities.FileTypeExtension {Value = ".img"});
        FileType.Register(_target, fileType, _iconStore, machineWide: false);

        string handler = Handlers.Single();
        GetValue(handler, "MimeType").Should().Be("image/x-high;");
        GetValue(handler, "NoDisplay").Should().Be("true");
        GetValue(handler, "Exec").Should().Be($"{Launcher} run {FeedTest.Test1Uri.ToStringRfc()} %f");
        Packages.Should().BeEmpty(because: "MIME type is already known to the system");
        File.Exists(MimeAppsPath).Should().BeFalse();

        FileType.Unregister(fileType, machineWide: false);
        Handlers.Should().BeEmpty();
    }

    [Fact]
    public void FileTypeGenerated()
    {
        var fileType = CreateFileType("a",
            new Capabilities.FileTypeExtension {Value = ".Foo"},
            new Capabilities.FileTypeExtension {Value = ".bar", MimeType = "application/x-bar"},
            new Capabilities.FileTypeExtension {Value = ".baz", MimeType = "text/plain"});
        FileType.Register(_target, fileType, _iconStore, machineWide: false);

        GetValue(Handlers.Single(), "MimeType").Should().Be("application/x-zeroinstall-foo;application/x-bar;application/x-zeroinstall-baz;");
        string package = File.ReadAllText(Packages.Single());
        package.Should().Contain("pattern=\"*.foo\"").And.Contain("type=\"application/x-bar\"").And.Contain("<sub-class-of type=\"text/plain\"");

        // Simulate update-mime-database
        File.WriteAllText(HomeFile(".local/share/mime/globs2"), "50:application/x-zeroinstall-foo:*.foo\n50:application/x-bar:*.bar\n50:application/x-zeroinstall-baz:*.baz\n");
        FileType.Register(_target, fileType, _iconStore, machineWide: false);
        File.ReadAllText(Packages.Single()).Should().Be(package, because: "reapplying should not mistake own MIME types for ones provided by the system");

        FileType.Unregister(fileType, machineWide: false);
        Handlers.Should().BeEmpty();
        Packages.Should().BeEmpty();

        FileType.Register(_target, fileType, _iconStore, machineWide: false);
        File.ReadAllText(Packages.Single()).Should().Be(package, because: "removing and adding again should not be confused by an outdated database");
    }

    [Fact]
    public void FileTypeFromOtherPackage()
    {
        Directory.CreateDirectory(PackagesDir);
        File.WriteAllText(Path.Combine(PackagesDir, "broken.xml"), "broken");
        File.WriteAllText(Path.Combine(PackagesDir, "other.xml"), """
            <mime-info xmlns="http://www.freedesktop.org/standards/shared-mime-info">
              <mime-type type="application/x-low"><glob pattern="*.foo" weight="40"/></mime-type>
              <mime-type type="application/x-other"><glob pattern="*.foo"/></mime-type>
            </mime-info>
            """);

        FileType.Register(_target, CreateFileType("a", new Capabilities.FileTypeExtension {Value = ".foo", MimeType = "application/x-foo"}), _iconStore, machineWide: false);
        GetValue(Handlers.Single(), "MimeType").Should().Be("application/x-other;application/x-foo;");
        Packages.Should().HaveCount(2, because: "MIME type is already provided by another package");
    }

    [Fact]
    public void FileTypeCaseSensitive()
    {
