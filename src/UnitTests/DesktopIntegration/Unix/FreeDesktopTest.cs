    [Fact]
    public void ContextMenuTerminal()
    {
        _target.Feed.EntryPoints[0].NeedsTerminal = true;
        var contextMenu = new Capabilities.ContextMenu
        {
            ID = "menu",
            Verbs = {new() {Name = "open", Command = _target.Feed.EntryPoints[0].Command}, new() {Name = "edit", Command = "gui"}}
        };
        string kdeDir = HomeFile(".local/share/kio/servicemenus"), nemoDir = HomeFile(".local/share/nemo/actions");
        string cli = Paths.Combine(Locations.InstallBase, "0install"), gui = CommandLine.GetLauncher(gui: true);

        ContextMenu.Apply(_target, contextMenu, _iconStore, machineWide: false);
        foreach (string dir in new[] {kdeDir, nemoDir})
        {
            string[] files = Directory.GetFiles(dir);
            files.Should().HaveCount(2);
            string terminal = files.Single(x => File.ReadAllText(x).Contains("\nTerminal=true\n"));
            GetValue(terminal, "Exec").Should().StartWith($"{new[] {cli}.ToExec()} run ");
            GetValue(files.Single(x => x != terminal), "Exec").Should().StartWith($"{new[] {gui}.ToExec()} run ");
        }

        _target.Feed.EntryPoints[0].NeedsTerminal = false;
        ContextMenu.Apply(_target, contextMenu, _iconStore, machineWide: false);
        File.ReadAllText(Directory.GetFiles(kdeDir).Single()).Should().NotContain("Terminal");

        ContextMenu.Remove(contextMenu, machineWide: false);
        Directory.GetFiles(kdeDir).Should().BeEmpty();
        Directory.GetFiles(nemoDir).Should().BeEmpty();
    }

    [Fact]
    public void NativeMessagingSharedManifest()
    {
        var capability = new Capabilities.BrowserNativeMessaging
        {
            ID = "host", Name = "my.host",
            Browsers = {Capabilities.KnownBrowsers.Chromium},
            BrowserExtensions = {new() {ID = "ext"}}
        };
        string manifestPath = HomeFile(".config/chromium/NativeMessagingHosts/my.host.json");
        string otherScript = Path.Combine(IntegrationManager.GetDir(machineWide: false, "browser-native-messaging", Capabilities.KnownBrowsers.Brave), "my.host");
        string otherManifest = $$"""{"name":"my.host","path":"{{otherScript}}"}""";
        Directory.CreateDirectory(Path.GetDirectoryName(manifestPath)!);
        File.WriteAllText(manifestPath, otherManifest);
        File.WriteAllText(otherScript, "");

        BrowserNativeMessagingHost.Register(_target, capability, machineWide: false);
        BrowserNativeMessagingHost.Unregister(capability, machineWide: false);
        File.ReadAllText(manifestPath).Should().Be(otherManifest, because: "manifests used by other browsers should not be touched");

        File.Delete(otherScript);
        BrowserNativeMessagingHost.Register(_target, capability, machineWide: false);
        JsonStorage.LoadJson<BrowserNativeMessagingManifest>(manifestPath).Path.Should().NotBe(otherScript, because: "orphaned manifests should be replaced");

        BrowserNativeMessagingHost.Unregister(capability, machineWide: false);
        File.Exists(manifestPath).Should().BeFalse();
    }

    [Fact]
    public void NativeMessaging()
    {
        var capability = new Capabilities.BrowserNativeMessaging
        {
            ID = "host", Name = "my.host", Command = "host",
            Browsers = {Capabilities.KnownBrowsers.Firefox, Capabilities.KnownBrowsers.Chrome},
            BrowserExtensions = {new() {ID = "ext"}}
        };
        string firefox = HomeFile(".mozilla/native-messaging-hosts/my.host.json"), chrome = HomeFile(".config/google-chrome/NativeMessagingHosts/my.host.json");
        Directory.CreateDirectory(Path.GetDirectoryName(chrome)!);
        File.WriteAllText(chrome, """{"name":"my.host","path":"/other"}""");

        BrowserNativeMessagingHost.Register(_target, capability, machineWide: false);
        var manifest = JsonStorage.LoadJson<BrowserNativeMessagingManifest>(firefox);
        manifest.AllowedExtensions.Should().Equal("ext");
        FileUtils.IsExecutable(manifest.Path).Should().BeTrue();
        File.ReadAllText(manifest.Path).Should().Be($"#!/bin/sh\nexec {Paths.Combine(Locations.InstallBase, "0install").EscapeArgumentPosix()} run --command host {FeedTest.Test1Uri.ToStringRfc()} \"$@\"\n");

        BrowserNativeMessagingHost.Unregister(capability, machineWide: false);
        File.Exists(firefox).Should().BeFalse();
        File.Exists(manifest.Path).Should().BeFalse();
        File.ReadAllText(chrome).Should().Contain("/other", because: "foreign manifests should not be touched");
    }
