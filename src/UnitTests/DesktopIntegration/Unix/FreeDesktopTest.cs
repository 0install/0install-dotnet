    [InlineData(null, "Video", "AudioVideo,Video")]
    [InlineData(null, "Bad;Name", "")]
    public void GetCategories(string? menuCategory, string feedCategories, string expected)
    {
        var feed = new Feed {Name = "MyApp"};
        feed.Categories.AddRange(feedCategories.Split(',').Select(x => new Category {Name = x}));
        string.Join(",", FreeDesktop.GetCategories(menuCategory, feed)).Should().Be(expected);
    }

    [Fact]
    public void UrlProtocolMimeTypes()
    {
        UrlProtocol.GetMimeTypes(new() {ID = "myapp"}).Should().Equal("x-scheme-handler/myapp");
        UrlProtocol.GetMimeTypes(new() {ID = "my app", KnownPrefixes = {new() {Value = "HTTP"}, new() {Value = "my scheme"}}}).Should().Equal("x-scheme-handler/http");
