        DefaultProgram.GetMimeTypes(Capabilities.DefaultProgram.ServiceMail).Should().Equal("x-scheme-handler/mailto");
        DefaultProgram.GetMimeTypes(Capabilities.DefaultProgram.ServiceJava).Should().BeEmpty();
    }

    private static readonly FeedTarget _target = new(new("http://example.com/a.xml"), new() {Name = "MyApp"});

    private static Capabilities.ContextMenu CreateContextMenu() => new()
    {
        ID = "menu",
        Descriptions = {"My &menu"},
        Extensions = {new() {Value = ".abc"}},
        Verbs =
        {
            new() {Name = "open", Descriptions = {"&Open"}},
            new() {Name = "edit", Command = "edit", SingleElementOnly = true}
        }
    };

    [Fact]
    public void KdeServiceMenu()
    {
        var contextMenu = CreateContextMenu();
        ContextMenu.GetKdeServiceMenu(_target, contextMenu, contextMenu.Verbs.Select(x => (x, (string?)null)).ToList(), ["application/x-abc"], "/bin/0install-gui", terminal: false)
                   .ToString().Should().Be("""
                                           # Generated by Zero Install

                                           [Desktop Entry]
                                           Type=Service
                                           X-KDE-ServiceTypes=KonqPopupMenu/Plugin
                                           MimeType=application/x-abc;
                                           Actions=verb0;verb1;
                                           X-KDE-Submenu=My menu

                                           [Desktop Action verb0]
                                           Name=Open
                                           Exec=/bin/0install-gui run http://example.com/a.xml %f

                                           [Desktop Action verb1]
                                           Name=edit
                                           Exec=/bin/0install-gui run --command edit http://example.com/a.xml %f

                                           """.Replace("\r\n", "\n"));
    }

    [Fact]
    public void NemoAction()
    {
        var contextMenu = CreateContextMenu();
        ContextMenu.GetNemoAction(_target, contextMenu, contextMenu.Verbs[0], icon: null, "/bin/0install-gui", terminal: false)
                   .ToString().Should().Be("""
                                           # Generated by Zero Install

                                           [Nemo Action]
                                           Active=true
                                           Name=Open
                                           Exec=/bin/0install-gui run http://example.com/a.xml %F
                                           Quote=double
                                           Selection=notnone
                                           Extensions=abc;

                                           """.Replace("\r\n", "\n"));
        ContextMenu.GetNemoAction(_target, contextMenu, contextMenu.Verbs[1], icon: null, "/bin/0install", terminal: true)
                   .ToString().Should().Contain("Selection=s\n").And.Contain("Terminal=true\n");
    }

    [Fact]
    public void NemoActionPercent()
    {
        var contextMenu = CreateContextMenu();
        contextMenu.Verbs[0].Descriptions.Clear();
        contextMenu.Verbs[0].Descriptions.Add("100%F");
        var target = new FeedTarget(new("http://example.com/%F6%20.xml"), new() {Name = "MyApp", Summaries = {"50%"}});
        ContextMenu.GetNemoAction(target, contextMenu, contextMenu.Verbs[0], icon: null, "/bin/0install-gui", terminal: false)
                   .ToString().Should().Contain("Exec=/bin/0install-gui run http://example.com/%%F6%%20.xml %F\n")
                              .And.Contain("Name=100%%F\n")
                              .And.Contain("Comment=50%%\n");
    }

    [Fact]
    public void NemoActionMultipleItems()
    {
        var contextMenu = CreateContextMenu();
        contextMenu.Verbs[0].Arguments.Add("${item}");
        contextMenu.Verbs[0].Arguments.Add("${item}");
        ContextMenu.GetNemoAction(_target, contextMenu, contextMenu.Verbs[0], icon: null, "/bin/0install-gui", terminal: false)
                   .ToString().Should().Contain("sh %F\n").And.Contain("Selection=s\n");
    }
}

/// <summary>
/// Contains test methods for <see cref="FreeDesktop"/> and related classes that modify the filesystem.
/// </summary>
public class FreeDesktopFileTest : TestWithHome
{
    private readonly FeedTarget _target;
    private readonly IIconStore _iconStore;

    public FreeDesktopFileTest() : base(macOS: false)
    {
        Directory.CreateDirectory(HomeFile("system/mime"));
        File.WriteAllText(HomeFile("system/mime/globs2"), "# Comment\n50:text/plain:*.txt\n50:image/x-low:*.img\n80:image/x-high:*.img\n50:application/octet-stream:*.bin\n");

        _target = new(FeedTest.Test1Uri, FeedTest.CreateTestFeed());
        var iconStore = new Mock<IIconStore>();
        iconStore.Setup(x => x.GetFresh(It.IsAny<Icon>())).Returns("/icons/test.png");
        _iconStore = iconStore.Object;
    }

    private static string Launcher => new[] {CommandLine.GetLauncher()}.ToExec();
    private string ApplicationsDir => HomeFile(".local/share/applications");
    private string PackagesDir => HomeFile(".local/share/mime/packages");
    private string MimeAppsPath => HomeFile(".config/mimeapps.list");

    private string[] Handlers => Directory.Exists(ApplicationsDir) ? Directory.GetFiles(ApplicationsDir, "zeroinstall-handler-*.desktop") : [];
    private string[] Packages => Directory.Exists(PackagesDir) ? Directory.GetFiles(PackagesDir) : [];

    private static string GetValue(string path, string key)
        => File.ReadAllLines(path).Single(x => x.StartsWith(key + "=", StringComparison.Ordinal))[(key.Length + 1)..];

    [Fact]
    public void MenuEntry()
    {
        var entry = new MenuEntry {Name = "My App", Category = "Development/MyApp", Command = Command.NameRun};
        FreeDesktop.Create(entry, _target, _iconStore, machineWide: false);
        FreeDesktop.Create(entry, _target, _iconStore, machineWide: false); // Overwrite own file

        string path = Path.Combine(ApplicationsDir, "zeroinstall-menu-Development%2fMyApp%2fMy%20App.desktop");
        GetValue(path, "Name").Should().Be("My App");
        GetValue(path, "Exec").Should().Be($"{Launcher} run --command run {FeedTest.Test1Uri.ToStringRfc()}");
        GetValue(path, "Icon").Should().Be("/icons/test.png");
        GetValue(path, "Categories").Should().StartWith("Development;");

        FreeDesktop.Remove(entry, machineWide: false);
        Directory.GetFiles(ApplicationsDir).Should().BeEmpty();
    }

    [Fact]
    public void TerminalApp()
    {
        _target.Feed.EntryPoints[0].NeedsTerminal = true;
        FreeDesktop.Create(new MenuEntry {Name = "My App"}, _target, _iconStore, machineWide: false);
        FileType.Register(_target, CreateFileType("a", new Capabilities.FileTypeExtension {Value = ".img"}), _iconStore, machineWide: false);

        string launcher = new[] {Paths.Combine(Locations.InstallBase, "0install")}.ToExec();
        foreach (string path in Directory.GetFiles(ApplicationsDir))
        {
            GetValue(path, "Terminal").Should().Be("true");
            GetValue(path, "Exec").Should().StartWith($"{launcher} run ");
        }
        Directory.GetFiles(ApplicationsDir).Should().HaveCount(2);
    }

