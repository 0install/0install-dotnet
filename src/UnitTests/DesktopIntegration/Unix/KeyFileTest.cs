namespace ZeroInstall.DesktopIntegration.Unix;

/// <summary>
/// Contains test methods for <see cref="KeyFile"/>.
/// </summary>
public class KeyFileTest
{
    [Fact]
    public void Format()
        => new KeyFile()
          .Group("Desktop Entry")
          .Add("Name", "My App")
          .Add("Comment", "")
          .Add("Terminal", false)
          .Add("NoDisplay", true)
          .Add("Categories", ["A", "B"])
          .Add("MimeType", [])
          .Group("Other")
          .Add("Key", "Value")
          .ToString().Should().Be("# Generated by Zero Install\n\n[Desktop Entry]\nName=My App\nNoDisplay=true\nCategories=A;B;\n\n[Other]\nKey=Value\n");

    [Fact]
    public void Escaping()
        => new KeyFile()
          .Add("Injection", "a\nExec=evil")
          .Add("Backslash", @"a\b")
          .Add("Space", " a")
          .Add("List", ["a;b"])
          .ToString().Should().EndWith("""
                                       Injection=a\nExec=evil
                                       Backslash=a\\b
                                       Space=\sa
                                       List=a\;b;

                                       """.Replace("\r\n", "\n"));
}
