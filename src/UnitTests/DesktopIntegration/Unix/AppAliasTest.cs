using System.Text.RegularExpressions;

namespace ZeroInstall.DesktopIntegration.Unix;

/// <summary>
/// Contains test methods for <see cref="AppAlias"/>.
/// </summary>
public class AppAliasTest
{
    [Fact]
    public void GetScript()
    {
        string script = AppAlias.GetScript(new("https://example.com/it's.xml"), "my-command");

        script.Should().StartWith("#!/bin/sh\n# Generated by Zero Install\n");
        script.Should().NotContain("\r");
        script.Should().Contain("exec 0install run --command my-command \"https://example.com/it's.xml\" \"$@\"\n");
    }

    [Fact]
    public void GetScriptNoCommand()
        => AppAlias.GetScript(FeedTest.Test1Uri, command: null)
                   .Should().Contain($"exec 0install run {FeedTest.Test1Uri.ToStringRfc().EscapeArgumentPosix()} \"$@\"\n");
}

/// <summary>
/// Contains test methods for <see cref="AppAlias"/> that modify the filesystem.
/// </summary>
public class AppAliasFileTest : TestWithHome
{
    private string AliasDir => Path.Combine(Home, ".local", "bin");
    private string AliasPath => Path.Combine(AliasDir, "my-alias");

    private static void Create(string aliasName = "my-alias")
        => AppAlias.Create(new(FeedTest.Test1Uri, FeedTest.CreateTestFeed()), command: null, aliasName, machineWide: false);

    [Fact]
    public void CreateAndRemove()
    {
        Create();
        File.Exists(AliasPath).Should().BeTrue();
        FileUtils.IsExecutable(AliasPath).Should().BeTrue();

        Create(); // Overwrite own file

        AppAlias.Remove("my-alias", machineWide: false);
        File.Exists(AliasPath).Should().BeFalse();
    }

    [Fact]
    public void CreateAddsToPath()
    {
        Create();
        File.ReadAllText(HomeFile(".profile")).Should().Contain("export PATH=\"$HOME/.local/bin:$PATH\"");

        Create();
        Regex.Matches(File.ReadAllText(HomeFile(".profile")), "export PATH").Count.Should().Be(1, because: "PATH should only be added once");
    }

    [Fact]
    public void CreateSkipsPathIfAlreadyPresent()
    {
        Environment.SetEnvironmentVariable("PATH", $"{AliasDir}:{OriginalPath}");
        Create();
        File.Exists(HomeFile(".profile")).Should().BeFalse();
    }

    [Fact]
    public void CreateUsesBashProfileInsteadOfProfile()
    {
        File.WriteAllText(HomeFile(".bash_profile"), "");
        Create();
        File.ReadAllText(HomeFile(".bash_profile")).Should().Contain("export PATH=\"$HOME/.local/bin:$PATH\"");
        File.Exists(HomeFile(".profile")).Should().BeFalse(because: "bash does not read .profile if .bash_profile exists");
    }

    [Fact]
    public void DoesNotTouchForeignFiles()
    {
        Directory.CreateDirectory(AliasDir);
        File.WriteAllText(AliasPath, "#!/bin/sh\necho foreign\n");

        Assert.Throws<IOException>(() => Create());
        AppAlias.Remove("my-alias", machineWide: false);

        File.ReadAllText(AliasPath).Should().Be("#!/bin/sh\necho foreign\n");
    }
}
