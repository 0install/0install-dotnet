using System.Text;

namespace ZeroInstall.DesktopIntegration.Unix;

/// <summary>
/// Contains control logic for applying <see cref="AccessPoints.AppAlias"/> on Unix systems.
/// </summary>
public static class AppAlias
{
    private const string
        Marker = "# Generated by Zero Install",
        UserDirRelative = ".local/bin";

    /// <summary>
    /// Creates an application alias in the current system.
    /// </summary>
    /// <param name="target">The application being integrated.</param>
    /// <param name="command">The command within <paramref name="target"/> the alias shall point to; can be <c>null</c>.</param>
    /// <param name="aliasName">The name of the alias to be created.</param>
    /// <param name="machineWide">Create the alias machine-wide instead of just for the current user.</param>
    /// <exception cref="OperationCanceledException">The user canceled the task.</exception>
    /// <exception cref="IOException">A problem occurred while writing to the filesystem.</exception>
    /// <exception cref="WebException">A problem occurred while downloading additional data (such as icons).</exception>
    /// <exception cref="UnauthorizedAccessException">Write access to the filesystem is not permitted.</exception>
    public static void Create(FeedTarget target, string? command, string aliasName, bool machineWide)
        => WriteScript(aliasName, machineWide, GetScript(target.Uri, command));

    /// <summary>
    /// Creates an application alias in the current system that runs an executable.
    /// </summary>
    /// <param name="executablePath">The path of the executable the alias shall point to.</param>
    /// <param name="aliasName">The name of the alias to be created.</param>
    /// <param name="machineWide">Create the alias machine-wide instead of just for the current user.</param>
    /// <exception cref="IOException">A problem occurred while writing to the filesystem.</exception>
    /// <exception cref="UnauthorizedAccessException">Write access to the filesystem is not permitted.</exception>
    public static void Create(string executablePath, string aliasName, bool machineWide)
        => WriteScript(aliasName, machineWide, GetScript(executablePath));

    private static void WriteScript(string aliasName, bool machineWide, string script)
    {
        string dirPath = GetDir(machineWide);
        string path = Paths.Combine(dirPath, aliasName);
        if (Directory.Exists(path) || File.Exists(path) && !IsGenerated(path))
            throw new IOException(string.Format(Resources.AliasFileNotOwned, path));

        Directory.CreateDirectory(dirPath);
        if (!machineWide) PathEnv.AddDir(dirPath);

        using var atomic = new AtomicWrite(path);
        File.WriteAllText(atomic.WritePath, script);
        FileUtils.SetExecutable(atomic.WritePath, true);
        atomic.Commit();
    }

    /// <summary>
    /// Generates a shell script that runs an executable directly.
    /// </summary>
    /// <param name="executablePath">The path of the executable to run.</param>
    private static string GetScript(string executablePath)
        => $"""
            #!/bin/sh
            {Marker}
            exec {executablePath.EscapeArgumentPosix()} "$@"

            """.ToUnixNewLine();

    /// <summary>
    /// Generates a shell script that runs a Zero Install application.
    /// </summary>
    /// <param name="uri">The URI of the application to run.</param>
    /// <param name="command">The command within the application to run; can be <c>null</c>.</param>
    public static string GetScript(FeedUri uri, string? command)
    {
        string fallbackPath = Paths.Combine(Locations.InstallBase, "0install");
        string fallback = File.Exists(fallbackPath)
            ? $"exec {RunWith(fallbackPath)} \"$@\""
            : $"echo {"0install not found in PATH".EscapeArgumentPosix()} >&2; exit 127";

        return $"""
            #!/bin/sh
            {Marker}
            if command -v {"0install"} >/dev/null 2>&1; then
              exec {RunWith("0install")} "$@"
            else
              {fallback}
            fi

            """.ToUnixNewLine();

        string RunWith(string exe) => CommandLine.GetRunArguments(uri, command).Prepend(exe).JoinEscapeArgumentsPosix();
    }

    /// <summary>
    /// Removes an application alias from the current system.
    /// </summary>
    /// <param name="aliasName">The name of the alias to be removed.</param>
    /// <param name="machineWide">The alias was created machine-wide instead of just for the current user.</param>
    /// <exception cref="IOException">A problem occurred while writing to the filesystem.</exception>
    /// <exception cref="UnauthorizedAccessException">Write access to the filesystem is not permitted.</exception>
    public static void Remove(string aliasName, bool machineWide)
    {
        string path = Paths.Combine(GetDir(machineWide), aliasName);
        if (!File.Exists(path)) return;

        if (IsGenerated(path)) File.Delete(path);
        else Log.Warn(string.Format(Resources.AliasFileNotOwned, path));
    }

    private static string GetDir(bool machineWide)
        => machineWide
            ? "/usr/local/bin"
            : Paths.Combine(Locations.HomeDir, UserDirRelative);

    private static bool IsGenerated(string path)
        => File.ReadLines(path, Encoding.UTF8).Skip(1).FirstOrDefault() == Marker;
}
